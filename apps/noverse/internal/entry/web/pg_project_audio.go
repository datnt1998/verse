// projectAudioFiles materializes just the small voice index for hosted
// projects. Conversion, clip validation, naming and presets still use the
// same file-mode implementation; samples themselves stay in the BlobStore.
// A project need not have a story to use these project-level resources.
type projectAudioFiles struct {
	layout    audio.Layout
	projectID pgtype.UUID
	cleanup   func()
}

func (g *Gateway) openProjectAudioFiles(ctx context.Context, user identity.User, p string, ref library.ProjectRef, config library.Config) (projectAudioFiles, error) {
	if ref.Dir != "" {
		layout, err := projectAudioLayout(g.RootPath(), ref.Dir)
		return projectAudioFiles{layout: layout, cleanup: func() {}}, err
	}
	if !g.pgMediaOK() {
		return projectAudioFiles{}, errors.New("kho đối tượng chưa cấu hình")
	}
	id, err := g.pgAudio.Nar.ProjectID(ctx, p, textActor(user))
	if err != nil {
		return projectAudioFiles{}, err
	}
	rows, err := g.pgAudio.Audio.ListVoices(ctx, id)
	if err != nil {
		return projectAudioFiles{}, err
	}
	root, err := os.MkdirTemp("", "ainovel-project-voices-*")
	if err != nil {
		return projectAudioFiles{}, err
	}
	assets := config.Dirs.Assets
	if assets == "" {
		assets = "tai-san"
	}
	files := projectAudioFiles{layout: audio.Layout{AssetsDir: filepath.Join(root, assets)}, projectID: id, cleanup: func() { _ = os.RemoveAll(root) }}
	voices := make([]audio.ProjectVoice, 0, len(rows))
	for _, row := range rows {
		var v audio.ProjectVoice
		if err = json.Unmarshal(row.Metadata, &v); err != nil {
			files.cleanup()
			return projectAudioFiles{}, err
		}
		v.ID = row.LegacyID
		if v.Name == "" {
			v.Name = v.ID
		}
		v.BuiltIn = false
		v.File = filepath.ToSlash(filepath.Join(assets, "giong", v.ID+".wav"))
		voices = append(voices, v)
	}
	if err = audio.WriteProjectVoices(files.layout, voices); err != nil {
		files.cleanup()
		return projectAudioFiles{}, err
	}
	return files, nil
}

// publishProjectVoice stores the normalized WAV generated by StoreVoice and
// links the existing audio_voices row to its immutable project asset blob.
func (g *Gateway) publishProjectVoice(ctx context.Context, files projectAudioFiles, voice audio.ProjectVoice) error {
	source := filepath.Join(files.layout.VoicesDir(), voice.ID+".wav")
	f, err := os.Open(source)
	if err != nil {
		return err
	}
	defer f.Close()
	h := sha256.New()
	size, err := io.Copy(h, f)
	if err != nil {
		return err
	}
	sha := hex.EncodeToString(h.Sum(nil))
	key, err := g.pgAudio.Keys.Asset(postgres.UUIDString(files.projectID), sha, "wav")
	if err != nil {
		return err
	}
	if _, err = f.Seek(0, io.SeekStart); err != nil {
		return err
	}
	blob, err := g.pgUpload(ctx, files.projectID, key, "audio/wav", f, sha, size)
	if err != nil {
		return err
	}
	_, err = g.pgAudio.Audio.UpsertVoice(ctx, files.projectID, voice.ID, voice, blob.ID)
	return err
}

func (g *Gateway) deleteHostedProjectVoice(ctx context.Context, id pgtype.UUID, legacy string) error {
	err := g.pgAudio.Audio.DeleteVoice(ctx, id, legacy)
	if errors.Is(err, postgres.ErrJobNotFound) {
		return library.ErrNotFound
	}
	return err
}

func (g *Gateway) serveHostedProjectVoiceSample(w http.ResponseWriter, r *http.Request, layout audio.Layout, id pgtype.UUID, legacy string) {
	voice, err := g.pgAudio.Audio.VoiceByLegacy(r.Context(), id, legacy)
	if errors.Is(err, postgres.ErrJobNotFound) {
		serveVoiceSample(w, r, layout, legacy)
		return
	}
	if err == nil && !voice.SampleBlobID.Valid {
		jsonError(w, http.StatusBadRequest, "Không phát được mẫu giọng này. Hãy thử lại hoặc chọn giọng khác.")
		return
	}
	if err != nil {
		audioError(w, err)
		return
	}
	blob, err := g.pgAudio.Audio.BlobByID(r.Context(), id, voice.SampleBlobID)
	if err != nil {
		audioError(w, err)
		return
	}
	if err = g.pgDownload(r.Context(), blob, filepath.Join(layout.VoicesDir(), legacy+".wav")); err != nil {
		audioError(w, err)
		return
	}
	serveVoiceSample(w, r, layout, legacy)
}

func (g *Gateway) serveHostedProjectPronunciations(w http.ResponseWriter, r *http.Request, user identity.User, p string) {
	if !g.pgMediaOK() {
		jsonError(w, 500, "kho đối tượng chưa cấu hình")
		return
	}
	repo := g.pgAudio.Audio.ProjectPronunciations()
	data, version, err := repo.Get(r.Context(), textActor(user), p)
	if err != nil {
		audioError(w, err)
		return
	}
	entries := []audio.Pronunciation{}
	if err = json.Unmarshal(data, &entries); err != nil {
		audioError(w, err)
		return
	}
	token := fmt.Sprintf("pg-pron-%d", version)
	switch r.Method {
	case http.MethodGet:
		if !checkIfMatchV(w, r, token, func() (any, error) { return entries, nil }) {
			return
		}
		writeJSON(w, 200, entries)
	case http.MethodPut:
		if !user.CanCollaborateProject(p) {
			jsonError(w, 403, "bạn không có quyền sửa")
			return
		}
		if !checkIfMatchV(w, r, token, func() (any, error) { return entries, nil }) {
			return
		}
		clean, err := decodeProjectPronunciations(r)
		if err != nil {
			jsonError(w, http.StatusBadRequest, err.Error())
			return
		}
		clean, err = audio.NormalizePronunciations(clean)
		if err != nil {
			audioError(w, err)
			return
		}
		body, err := json.Marshal(clean)
		if err != nil {
			audioError(w, err)
			return
		}
		expected := strings.Trim(strings.TrimSpace(r.Header.Get("If-Match")), "\"")
		version, err = repo.Put(r.Context(), textActor(user), p, body, expected)
		if err != nil {
			audioError(w, err)
			return
		}
		g.projectChanged(p)
		writeVersionToken(w, fmt.Sprintf("pg-pron-%d", version))
		writeJSON(w, 200, clean)
	default:
		jsonError(w, http.StatusNotFound, "không tìm thấy")
	}
}

// decodeProjectPronunciations accepts both historical HTTP shapes, then uses
// the same dictionary validator on either backend.
func decodeProjectPronunciations(r *http.Request) ([]audio.Pronunciation, error) {
	raw, err := io.ReadAll(io.LimitReader(r.Body, (1<<20)+1))
	if err != nil {
		return nil, err
	}
	if len(raw) > 1<<20 {
		return nil, errors.New("Dữ liệu gửi lên quá lớn")
	}
	var entries []audio.Pronunciation
	if err := json.Unmarshal(raw, &entries); err != nil {
		var wrapped struct {
			Entries []audio.Pronunciation `json:"entries"`
		}
		if err := json.Unmarshal(raw, &wrapped); err != nil {
			return nil, err
		}
		entries = wrapped.Entries
	}
	return entries, nil
}

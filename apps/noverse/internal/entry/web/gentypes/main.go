// Command gentypes renders web/src/api/types.gen.ts from the Go DTOs of the web
// package. Run `go generate ./internal/entry/web` after changing a DTO; the drift
// test in this package fails when the checked-in file is stale.
// The input is api_dto.go in the parent package: response roots, the TypeScript
// name of every nested struct, closed value sets and field-type overrides.
package main

import (
	"bytes"
	"flag"
	"fmt"
	"os"
	"path"
	"path/filepath"
	"reflect"
	"sort"
	"strings"
	"time"

	"github.com/datnt1998/verse/apps/noverse/internal/entry/web"
)

var timeType = reflect.TypeOf(time.Time{})

func main() {
	check := flag.Bool("check", false, "exit non-zero when web/src/api/types.gen.ts is stale")
	flag.Parse()

	out, err := generate()
	if err != nil {
		fail(err)
	}
	path, err := outputPath()
	if err != nil {
		fail(err)
	}
	if *check {
		existing, err := os.ReadFile(path)
		if err != nil {
			fail(fmt.Errorf("read %s: %w (run go generate ./internal/entry/web)", path, err))
		}
		if !bytes.Equal(existing, out) {
			fail(fmt.Errorf("%s is stale: run go generate ./internal/entry/web", path))
		}
		return
	}
	if err := os.WriteFile(path, out, 0o644); err != nil {
		fail(err)
	}
	fmt.Println("wrote", path)
}

func fail(err error) {
	fmt.Fprintln(os.Stderr, "gentypes:", err)
	os.Exit(1)
}

// outputPath resolves web/src/api/types.gen.ts from the app root (the nearest
// ancestor holding web/package.json; go.mod sits above it in the monorepo), so
// the generator works from `go generate` (cwd = package dir) and from `go test`.
func outputPath() (string, error) {
	dir, err := os.Getwd()
	if err != nil {
		return "", err
	}
	for {
		if _, err := os.Stat(filepath.Join(dir, "web", "package.json")); err == nil {
			return filepath.Join(dir, "web", "src", "api", "types.gen.ts"), nil
		}
		parent := filepath.Dir(dir)
		if parent == dir {
			return "", fmt.Errorf("web/package.json not found above %s", dir)
		}
		dir = parent
	}
}

type tsField struct {
	Name     string
	Type     string
	Optional bool
}

// decl is one pending TypeScript declaration: a struct rendering.
type decl struct {
	ts     string
	goType reflect.Type
}

type generator struct {
	names        map[reflect.Type]string
	tsOwners     map[string]reflect.Type
	queue        []decl
	queued       map[string]bool
	emitted      map[string]bool
	enums        map[reflect.Type]map[string]*web.APIEnum
	usedEnums    map[*web.APIEnum]bool
	overrides    map[reflect.Type]map[string]*web.APIFieldType
	usedOverride map[*web.APIFieldType]bool
}

func generate() ([]byte, error) {
	g := &generator{
		names:        map[reflect.Type]string{},
		tsOwners:     map[string]reflect.Type{},
		queued:       map[string]bool{},
		emitted:      map[string]bool{},
		enums:        map[reflect.Type]map[string]*web.APIEnum{},
		usedEnums:    map[*web.APIEnum]bool{},
		overrides:    map[reflect.Type]map[string]*web.APIFieldType{},
		usedOverride: map[*web.APIFieldType]bool{},
	}
	if err := g.loadNames(); err != nil {
		return nil, err
	}
	if err := g.loadEnums(); err != nil {
		return nil, err
	}
	if err := g.loadOverrides(); err != nil {
		return nil, err
	}
	if err := g.loadRoots(); err != nil {
		return nil, err
	}

	var header strings.Builder
	header.WriteString("// Code generated by go generate ./internal/entry/web; DO NOT EDIT.\n")
	header.WriteString("// Source: internal/entry/web/api_dto.go and the Go DTOs it names.\n")
	header.WriteString("// Regenerate: go generate ./internal/entry/web\n\n")

	var decls strings.Builder
	for len(g.queue) > 0 {
		d := g.queue[0]
		g.queue = g.queue[1:]
		if g.emitted[d.ts] {
			continue
		}
		g.emitted[d.ts] = true
		text, err := g.renderStruct(d)
		if err != nil {
			return nil, err
		}
		decls.WriteString(text)
	}

	for i := range web.APIEnums {
		enum := &web.APIEnums[i]
		if !g.usedEnums[enum] {
			return nil, fmt.Errorf("enum %s is declared in APIEnums but no field uses it", enum.TS)
		}
		fmt.Fprintf(&header, "// %s is the closed set of values the backend writes for these fields.\n", enum.TS)
		fmt.Fprintf(&header, "export type %s = %s\n\n", enum.TS, tsUnion(enum.Values))
	}

	for t, name := range g.names {
		if !g.emitted[name] {
			return nil, fmt.Errorf("TypeScript name %q for %s is never reached by a response", name, typeKey(t))
		}
	}
	for i := range web.APIFieldTypes {
		override := &web.APIFieldTypes[i]
		if !g.usedOverride[override] {
			return nil, fmt.Errorf("APIFieldTypes entry %s.%s is never emitted", typeKey(override.Owner), override.Name)
		}
	}

	out := header.String() + decls.String()
	return []byte(strings.TrimRight(out, "\n") + "\n"), nil
}

func (g *generator) loadNames() error {
	for t, name := range web.APITSTypeNames {
		if t.Kind() != reflect.Struct {
			return fmt.Errorf("%s is not a struct", typeKey(t))
		}
		if prev, ok := g.tsOwners[name]; ok && prev != t {
			return fmt.Errorf("TypeScript name %q used by both %s and %s", name, typeKey(prev), typeKey(t))
		}
		g.names[t] = name
		g.tsOwners[name] = t
	}
	return nil
}

func (g *generator) loadEnums() error {
	for i := range web.APIEnums {
		enum := &web.APIEnums[i]
		if len(enum.Values) == 0 {
			return fmt.Errorf("enum %s has no values", enum.TS)
		}
		if prev, ok := g.tsOwners[enum.TS]; ok {
			return fmt.Errorf("TypeScript name %q used by both enum and %s", enum.TS, typeKey(prev))
		}
		g.tsOwners[enum.TS] = nil
		for _, field := range enum.Fields {
			if err := checkField(field.Owner, field.Name, reflect.String); err != nil {
				return fmt.Errorf("enum %s: %w", enum.TS, err)
			}
			if g.enums[field.Owner] == nil {
				g.enums[field.Owner] = map[string]*web.APIEnum{}
			}
			if prev, ok := g.enums[field.Owner][field.Name]; ok {
				return fmt.Errorf("%s.%s is in both enum %s and %s", typeKey(field.Owner), field.Name, prev.TS, enum.TS)
			}
			g.enums[field.Owner][field.Name] = enum
		}
	}
	return nil
}

func (g *generator) loadOverrides() error {
	for i := range web.APIFieldTypes {
		override := &web.APIFieldTypes[i]
		if strings.TrimSpace(override.TS) == "" {
			return fmt.Errorf("APIFieldTypes %s.%s has no TypeScript type", typeKey(override.Owner), override.Name)
		}
		if err := checkField(override.Owner, override.Name, reflect.Invalid); err != nil {
			return fmt.Errorf("APIFieldTypes: %w", err)
		}
		if enum := g.enums[override.Owner][override.Name]; enum != nil {
			return fmt.Errorf("%s.%s has both an enum (%s) and a field type", typeKey(override.Owner), override.Name, enum.TS)
		}
		if g.overrides[override.Owner] == nil {
			g.overrides[override.Owner] = map[string]*web.APIFieldType{}
		}
		g.overrides[override.Owner][override.Name] = override
	}
	return nil
}

func checkField(owner reflect.Type, name string, want reflect.Kind) error {
	if owner == nil || owner.Kind() != reflect.Struct {
		return fmt.Errorf("%s is not a struct", typeKey(owner))
	}
	field, ok := owner.FieldByName(name)
	if !ok {
		return fmt.Errorf("%s has no field %s", typeKey(owner), name)
	}
	if want != reflect.Invalid && field.Type.Kind() != want {
		return fmt.Errorf("%s.%s is %s, want %s", typeKey(owner), name, field.Type.Kind(), want)
	}
	return nil
}

func (g *generator) loadRoots() error {
	for _, dto := range web.APIDTOs {
		t := deref(reflect.TypeOf(dto.Value))
		if t.Kind() != reflect.Struct {
			return fmt.Errorf("APIDTO %s is %s, want a struct", dto.TS, typeKey(t))
		}
		if prev, ok := g.names[t]; ok && prev != dto.TS {
			return fmt.Errorf("APIDTO %s conflicts with TypeScript name %q for %s", dto.TS, prev, typeKey(t))
		}
		if prev, ok := g.tsOwners[dto.TS]; ok && prev != t {
			return fmt.Errorf("APIDTO name %s used by both %s and %s", dto.TS, typeKey(prev), typeKey(t))
		}
		g.names[t] = dto.TS
		g.tsOwners[dto.TS] = t
		if err := g.enqueue(t); err != nil {
			return err
		}
	}
	return nil
}

// enqueue schedules the struct rendering that publishes t under its TypeScript name.
func (g *generator) enqueue(t reflect.Type) error {
	return g.push(decl{ts: g.names[t], goType: t})
}

func (g *generator) push(d decl) error {
	if g.queued[d.ts] {
		return nil
	}
	g.queued[d.ts] = true
	g.queue = append(g.queue, d)
	return nil
}

func (g *generator) ref(t reflect.Type) (string, error) {
	name, ok := g.names[t]
	if !ok {
		return "", fmt.Errorf("no TypeScript name for %s: add it to APITSTypeNames", typeKey(t))
	}
	if prev, ok := g.tsOwners[name]; ok && prev != t {
		return "", fmt.Errorf("TypeScript name %q used by both %s and %s", name, typeKey(prev), typeKey(t))
	}
	g.tsOwners[name] = t
	if err := g.enqueue(t); err != nil {
		return "", err
	}
	return name, nil
}

func (g *generator) renderStruct(d decl) (string, error) {
	var fields []tsField
	if err := g.collect(d.goType, &fields); err != nil {
		return "", err
	}
	var b strings.Builder
	fmt.Fprintf(&b, "export type %s = {\n", d.ts)
	for _, field := range fields {
		optional := ""
		if field.Optional {
			optional = "?"
		}
		fmt.Fprintf(&b, "  %s%s: %s\n", field.Name, optional, field.Type)
	}
	b.WriteString("}\n\n")
	return b.String(), nil
}

// collect flattens a struct the way encoding/json does: embedded structs without
// a tag contribute their fields in place, unexported and `json:"-"` fields are
// skipped.
func (g *generator) collect(t reflect.Type, out *[]tsField) error {
	for i := range t.NumField() {
		field := t.Field(i)
		tag := field.Tag.Get("json")
		// An embedded unexported struct type still publishes its exported fields:
		// encoding/json only drops unexported *fields*, so flatten before the
		// PkgPath check (qualityIssueAPI and universeKeptCheck rely on this).
		if field.Anonymous && tag == "" {
			embedded := deref(field.Type)
			if embedded.Kind() != reflect.Struct {
				return fmt.Errorf("embedded field %s.%s is not a struct", typeKey(t), field.Name)
			}
			if err := g.collect(embedded, out); err != nil {
				return err
			}
			continue
		}
		if field.PkgPath != "" {
			continue
		}
		name, omitted := jsonName(field, tag)
		if name == "-" {
			continue
		}
		typ, err := g.fieldType(t, field, omitted)
		if err != nil {
			return err
		}
		*out = append(*out, tsField{Name: name, Type: typ, Optional: omitted})
	}
	return nil
}

func (g *generator) fieldType(owner reflect.Type, field reflect.StructField, omitted bool) (string, error) {
	if override := g.overrides[owner][field.Name]; override != nil {
		if err := g.discover(field.Type); err != nil {
			return "", fmt.Errorf("%s.%s: %w", typeKey(owner), field.Name, err)
		}
		g.usedOverride[override] = true
		return override.TS, nil
	}
	ptr := field.Type.Kind() == reflect.Ptr
	typ, err := g.tsType(deref(field.Type))
	if err != nil {
		return "", fmt.Errorf("%s.%s: %w", typeKey(owner), field.Name, err)
	}
	if ptr && !omitted {
		typ += " | null"
	}
	if enum := g.enums[owner][field.Name]; enum != nil {
		g.usedEnums[enum] = true
		typ = enum.TS
	}
	return typ, nil
}

// discover enqueues the named structs behind a field even when the field's TS
// type comes from an override.
func (g *generator) discover(t reflect.Type) error {
	switch t.Kind() {
	case reflect.Ptr, reflect.Slice, reflect.Array:
		return g.discover(t.Elem())
	case reflect.Map:
		if err := g.discover(t.Key()); err != nil {
			return err
		}
		return g.discover(t.Elem())
	case reflect.Struct:
		if t == timeType {
			return nil
		}
		_, err := g.ref(t)
		return err
	default:
		return nil
	}
}

func (g *generator) tsType(t reflect.Type) (string, error) {
	if t == timeType {
		return "string", nil
	}
	switch t.Kind() {
	case reflect.Ptr:
		inner, err := g.tsType(t.Elem())
		if err != nil {
			return "", err
		}
		return inner + " | null", nil
	case reflect.Slice, reflect.Array:
		inner, err := g.tsType(t.Elem())
		if err != nil {
			return "", err
		}
		return parenthesize(inner) + "[]", nil
	case reflect.Map:
		key, err := g.tsType(t.Key())
		if err != nil {
			return "", err
		}
		value, err := g.tsType(t.Elem())
		if err != nil {
			return "", err
		}
		return fmt.Sprintf("Record<%s, %s>", key, value), nil
	case reflect.Interface:
		return "unknown", nil
	case reflect.String:
		return "string", nil
	case reflect.Bool:
		return "boolean", nil
	case reflect.Int, reflect.Int8, reflect.Int16, reflect.Int32, reflect.Int64,
		reflect.Uint, reflect.Uint8, reflect.Uint16, reflect.Uint32, reflect.Uint64,
		reflect.Float32, reflect.Float64:
		return "number", nil
	case reflect.Struct:
		return g.ref(t)
	default:
		return "", fmt.Errorf("unsupported Go type %s", t)
	}
}

func jsonName(field reflect.StructField, tag string) (string, bool) {
	if tag == "" {
		return lowerFirst(field.Name), false
	}
	parts := strings.Split(tag, ",")
	name := parts[0]
	if name == "" {
		name = lowerFirst(field.Name)
	}
	omitted := false
	for _, opt := range parts[1:] {
		if opt == "omitempty" {
			omitted = true
		}
	}
	return name, omitted
}

func deref(t reflect.Type) reflect.Type {
	for t.Kind() == reflect.Ptr {
		t = t.Elem()
	}
	return t
}

func lowerFirst(s string) string {
	if s == "" {
		return s
	}
	return strings.ToLower(s[:1]) + s[1:]
}

func parenthesize(typ string) string {
	if strings.Contains(typ, " | ") || strings.Contains(typ, " & ") {
		return "(" + typ + ")"
	}
	return typ
}

func tsUnion(values []string) string {
	quoted := make([]string, 0, len(values))
	for _, value := range values {
		quoted = append(quoted, "'"+strings.ReplaceAll(value, "'", `\'`)+"'")
	}
	sort.Strings(quoted)
	return strings.Join(quoted, " | ")
}

func typeKey(t reflect.Type) string {
	if t == nil {
		return "<nil>"
	}
	name := t.Name()
	if name == "" {
		name = t.String()
	}
	pkg := t.PkgPath()
	if pkg == "" {
		return name
	}
	return path.Base(pkg) + "." + name
}

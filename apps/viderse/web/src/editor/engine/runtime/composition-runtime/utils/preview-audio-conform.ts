import { blobUrlManager } from '@editor/infrastructure/browser/blob-url-manager'
import {
  onMediaContentChange,
  resolveMediaIdentity,
} from '@editor/infrastructure/storage/workspace-fs/cache-identity'
import { exists, readBlob, removeEntry, writeBlob } from '@editor/infrastructure/storage/workspace-fs/fs-primitives'
import { previewAudioPath } from '@editor/infrastructure/storage/workspace-fs/paths'
import { requireWorkspaceRoot } from '@editor/infrastructure/storage/workspace-fs/root'
import { createLogger } from '@editor/shared/logging/logger'
import type { CacheIdentity } from '@editor/storage/opfs-cache'
import type { MediaMetadata } from '@editor/types/storage'
import { audioBufferToWavBlob, int16StereoToWavBlob } from './audio-buffer-wav'

/**
 * Preview audio conform: a WAV rendition of a media's decoded audio, kept in
 * the disposable OPFS cache (`media/{id}/cache/preview-audio.wav`, versioned by
 * the server content hash). Its presence in the cache is the only "conformed"
 * marker — nothing durable is written to media metadata, and an evicted or
 * replaced rendition is simply regenerated by the next decode.
 */

const log = createLogger('PreviewAudioConform')

const PREVIEW_AUDIO_CONFORM_MIME_TYPE = 'audio/wav'

const pendingPreviewAudioConformLoads = new Map<string, Promise<string | null>>()
const pendingPreviewAudioConformPersists = new Map<string, Promise<void>>()

function getPreviewAudioConformCacheKey(mediaId: string): string {
  return `preview-audio:${mediaId}`
}

function forgetPreviewAudioConformMemory(mediaId: string): void {
  pendingPreviewAudioConformLoads.delete(mediaId)
  pendingPreviewAudioConformPersists.delete(mediaId)
  blobUrlManager.invalidate(getPreviewAudioConformCacheKey(mediaId))
}

// The blob URL and in-flight maps are keyed by mediaId; once the source bytes
// are replaced they describe audio that no longer exists.
onMediaContentChange(({ mediaId }) => forgetPreviewAudioConformMemory(mediaId))

/**
 * True when the conform WAV is present in the cache for the media's current
 * content. Callers use this to skip the (expensive) decode + AudioBuffer
 * rebuild that would otherwise run purely to feed a conform that is already
 * cached — the dominant source of jank when audio clips scroll back into view.
 */
export async function isPreviewAudioConformed(mediaId: string): Promise<boolean> {
  try {
    return await exists(requireWorkspaceRoot(), previewAudioPath(mediaId))
  } catch {
    return false
  }
}

export async function resolvePreviewAudioConformUrl(mediaId: string): Promise<string | null> {
  const cacheKey = getPreviewAudioConformCacheKey(mediaId)
  const cached = blobUrlManager.get(cacheKey)
  if (cached) {
    return cached
  }

  const pending = pendingPreviewAudioConformLoads.get(mediaId)
  if (pending) {
    return pending
  }

  const promise = (async () => {
    try {
      const blob = await readBlob(requireWorkspaceRoot(), previewAudioPath(mediaId))
      if (!blob) {
        return null
      }
      return blobUrlManager.acquire(
        cacheKey,
        new Blob([await blob.arrayBuffer()], { type: PREVIEW_AUDIO_CONFORM_MIME_TYPE }),
      )
    } catch (err) {
      log.warn('Failed to resolve preview audio conform asset', { mediaId, err })
      return null
    } finally {
      pendingPreviewAudioConformLoads.delete(mediaId)
    }
  })()

  pendingPreviewAudioConformLoads.set(mediaId, promise)
  return promise
}

/**
 * Encode and persist the conform WAV. `buildBlob` is a lazy factory so the
 * (potentially expensive) encode only runs once the in-flight guard and the
 * already-conformed check have cleared — never speculatively per call.
 * `identity` pins the write to the content the audio was decoded from.
 */
function persistConform(
  mediaId: string,
  buildBlob: () => Blob,
  identity?: CacheIdentity,
): Promise<void> {
  const pending = pendingPreviewAudioConformPersists.get(mediaId)
  if (pending) {
    return pending
  }

  const promise = (async () => {
    // Already conformed in a prior visit/session — the WAV is in the cache.
    // Clips re-enter the viewport constantly while scrolling and each remount
    // retries the conform; re-encoding the whole WAV every time is pure
    // main-thread waste.
    const pinned = identity ?? (await resolveMediaIdentity(mediaId))
    if (await exists(requireWorkspaceRoot(), previewAudioPath(mediaId))) {
      return
    }

    const cacheKey = getPreviewAudioConformCacheKey(mediaId)
    const wavBlob = buildBlob()
    if (!blobUrlManager.get(cacheKey)) {
      blobUrlManager.acquire(cacheKey, wavBlob)
    }

    await writeBlob(
      requireWorkspaceRoot(),
      previewAudioPath(mediaId),
      new Uint8Array(await wavBlob.arrayBuffer()),
      pinned,
    )
  })()
    .catch((err) => {
      log.warn('Failed to persist preview audio conform asset', { mediaId, err })
    })
    .finally(() => {
      pendingPreviewAudioConformPersists.delete(mediaId)
    })

  pendingPreviewAudioConformPersists.set(mediaId, promise)
  return promise
}

export function persistPreviewAudioConform(
  mediaId: string,
  buffer: AudioBuffer,
  identity?: CacheIdentity,
): Promise<void> {
  return persistConform(mediaId, () => audioBufferToWavBlob(buffer), identity)
}

/**
 * Conform straight from persisted Int16 bins, avoiding the AudioBuffer
 * Int16→Float32→Int16 round-trip. Preferred on the fresh-decode path where the
 * raw Int16 samples are already in hand.
 */
export function persistPreviewAudioConformFromInt16(
  mediaId: string,
  left: Int16Array,
  right: Int16Array,
  sampleRate: number,
  identity?: CacheIdentity,
): Promise<void> {
  return persistConform(mediaId, () => int16StereoToWavBlob(left, right, sampleRate), identity)
}

export async function deletePreviewAudioConform(mediaOrId: MediaMetadata | string): Promise<void> {
  const mediaId = typeof mediaOrId === 'string' ? mediaOrId : mediaOrId.id

  forgetPreviewAudioConformMemory(mediaId)
  await removeEntry(requireWorkspaceRoot(), previewAudioPath(mediaId))
}
